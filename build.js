// Generates static pages from the data files:
//   projects/<slug>/index.html · 404.html · sitemap.xml · robots.txt
// Run after editing assets/js/projects.js or data.js:  node build.js
const fs = require('node:fs');
const path = require('node:path');

const C = require('./assets/js/core.js');
const D = require('./assets/js/data.js');
const PR = require('./assets/js/projects.js');
const renderProject = require('./assets/js/project-view.js');

const root = __dirname;
const SITE = D.siteUrl;
const { esc, ui } = C;
const write = (rel, content) => {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('  wrote', rel);
};

const FONTS = 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Thai:wght@400;500;600;700&family=Plus+Jakarta+Sans:wght@400;500;600;700;800&family=Playpen+Sans:wght@400;600&family=JetBrains+Mono:wght@400;500&display=swap';

function head({ title, desc, url, image, jsonld }) {
  return `<meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}" />
  <meta name="theme-color" content="#ffffff" />
  ${url ? `<link rel="canonical" href="${url}" />` : '<meta name="robots" content="noindex" />'}
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="Suphakit Kaeokaemthong" />
  <meta property="og:title" content="${esc(title)}" />
  <meta property="og:description" content="${esc(desc)}" />
  ${url ? `<meta property="og:url" content="${url}" />` : ''}
  <meta property="og:image" content="${image}" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:image" content="${image}" />
  <link rel="icon" href="/assets/img/favicon.svg" type="image/svg+xml" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="${FONTS}" rel="stylesheet" />
  <link rel="stylesheet" href="/assets/css/style.css" />${jsonld ? `
  <script type="application/ld+json">${JSON.stringify(jsonld)}</script>` : ''}`;
}

function nav(lang) {
  return `<header class="nav is-sub" id="nav">
    <div class="nav-bar">
      <a class="nav-logo" href="/" data-i18n-attr="aria-label:nav.home" aria-label="${esc(ui('nav.home', lang))}">
        <span>suphakit</span>
      </a>
      <nav class="nav-links" aria-label="Main">
        <a href="/#work" data-i18n="nav.work">${ui('nav.work', lang)}</a>
        <a href="/#experience" data-i18n="nav.experience">${ui('nav.experience', lang)}</a>
        <a href="/#skills" data-i18n="nav.skills">${ui('nav.skills', lang)}</a>
        <a href="#contact" data-i18n="nav.contact">${ui('nav.contact', lang)}</a>
      </nav>
      <div class="nav-right">
        <span class="status-pill"><i class="dot"></i><span data-bind="status">${esc(C.t(D.profile.status, lang))}</span></span>
        <button class="lang-toggle" type="button" data-i18n-attr="aria-label:nav.lang" aria-label="${esc(ui('nav.lang', lang))}">
          <svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><circle cx="12" cy="12" r="9" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M3 12h18M12 3c2.5 2.6 3.8 5.6 3.8 9s-1.3 6.4-3.8 9c-2.5-2.6-3.8-5.6-3.8-9S9.5 5.6 12 3z" fill="none" stroke="currentColor" stroke-width="1.6"/></svg>
          <span data-l="th"${lang === 'th' ? ' class="on"' : ''}>TH</span><span data-l="en"${lang === 'en' ? ' class="on"' : ''}>EN</span>
        </button>
        <a class="btn btn-dark btn-sm" href="${D.links.resume}" target="_blank" rel="noopener">Resume</a>
      </div>
    </div>
  </header>`;
}

const footer = `<footer class="footer">
    <span>© <span id="year">${new Date().getFullYear()}</span> Suphakit Kaeokaemthong · Khon Kaen, TH</span>
    <a href="#top" data-i18n="footer.top">${ui('footer.top', 'en')}</a>
  </footer>`;

const BANNER = '<!-- Generated by build.js from assets/js/projects.js — edit the data, then run `node build.js` -->';

/* ---------- project pages ---------- */
console.log('Building pages…');
for (const p of PR) {
  const url = `${SITE}/projects/${p.slug}`;
  const desc = C.t(p.summary, 'en');
  const html = `<!doctype html>
${BANNER}
<html lang="en">
<head>
  ${head({
    title: `${p.title} — Suphakit Kaeokaemthong`,
    desc,
    url,
    image: `${SITE}/assets/og/${p.slug}.jpg`,
    jsonld: {
      '@context': 'https://schema.org',
      '@type': 'CreativeWork',
      name: p.title,
      description: desc,
      url,
      image: `${SITE}/assets/img/projects/${p.cover}.webp`,
      dateCreated: String(p.year),
      keywords: p.stack.join(', '),
      author: { '@type': 'Person', name: D.profile.name, url: SITE + '/' },
      ...(p.github ? { codeRepository: p.github } : {}),
    },
  })}
</head>
<body data-slug="${p.slug}">
  ${nav('en')}
  <main class="pj" id="pj">${renderProject(p.slug, 'en', { C, D, PR })}
  </main>
  ${footer}

  <dialog class="lightbox" id="lightbox" aria-label="Screenshot">
    <figure><img src="" alt="" /><figcaption></figcaption></figure>
    <button type="button" class="lb-btn lb-prev" data-nav="-1" aria-label="Previous">←</button>
    <button type="button" class="lb-btn lb-next" data-nav="1" aria-label="Next">→</button>
    <button type="button" class="lb-btn lb-close" data-close aria-label="Close">✕</button>
  </dialog>

  <script src="/assets/js/core.js"></script>
  <script src="/assets/js/data.js"></script>
  <script src="/assets/js/projects.js"></script>
  <script src="/assets/js/project-view.js"></script>
  <script src="/assets/js/project.js"></script>
</body>
</html>
`;
  write(`projects/${p.slug}/index.html`, html);
}

/* ---------- 404 ---------- */
write('404.html', `<!doctype html>
${BANNER}
<html lang="en">
<head>
  ${head({ title: 'Not found — Suphakit Kaeokaemthong', desc: ui('nf.body', 'en'), image: `${SITE}/assets/og/og-home.jpg` })}
</head>
<body>
  ${nav('en')}
  <main class="nf">
    <div class="nf-notes" aria-hidden="true">
      ${PR.slice(0, 3).map((p, i) => `<a class="nf-card" href="/projects/${p.slug}" style="--r:${[-8, 5, -3][i]}deg"><img src="/assets/img/projects/${p.cover}-sm.webp" alt=""><b>${esc(p.title)}</b></a>`).join('')}
    </div>
    <span class="nf-code hand">404</span>
    <h1 data-i18n="nf.title">${ui('nf.title', 'en')}</h1>
    <p data-i18n="nf.body">${ui('nf.body', 'en')}</p>
    <a class="btn btn-dark" href="/" data-i18n="nav.home">${ui('nav.home', 'en')}</a>
  </main>
  <script src="/assets/js/core.js"></script>
  <script src="/assets/js/data.js"></script>
  <script>CORE.applyStatic(CORE.lang); document.querySelectorAll('[data-bind="status"]').forEach(function (el) { el.textContent = CORE.t(PORTFOLIO.profile.status, CORE.lang); }); CORE.onLang(function (l) { document.querySelectorAll('[data-bind="status"]').forEach(function (el) { el.textContent = CORE.t(PORTFOLIO.profile.status, l); }); });</script>
</body>
</html>
`);

/* ---------- sitemap + robots ---------- */
const today = new Date().toISOString().slice(0, 10);
const urls = [`${SITE}/`, ...PR.map((p) => `${SITE}/projects/${p.slug}`)];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);
write('robots.txt', `User-agent: *
Allow: /

Sitemap: ${SITE}/sitemap.xml
`);
console.log('Done.');
